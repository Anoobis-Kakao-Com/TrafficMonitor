# Device glyphs of the Bluetooth battery plugin. One definition -> C++ include file (BtGlyphs.inc) and a preview png.
# Every glyph is drawn in a unit box (0..1 x 0..1); the plugin scales the box to 6.6 x 6.6 px of the 37 x 16 icon grid.
# ops: R filled round rect (x y w h r) | O outlined round rect | L line (x1 y1 x2 y2) | A arc outline (x y w h start sweep)
#      E filled ellipse (x y w h)     | C outlined ellipse     | T filled triangle (x1 y1 x2 y2 x3 y3)
