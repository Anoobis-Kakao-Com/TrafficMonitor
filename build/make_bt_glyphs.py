# Bluetooth mark: polyline in a 4.4 x 6.6 box (points as fractions)
BT_MARK = [(0.0, 0.27), (1.0, 0.73), (0.5, 1.0), (0.5, 0.0), (1.0, 0.27), (0.0, 0.73)]

def cpp():
    out = ['// generated by make_bt_glyphs.py - do not edit by hand\n']
    for name, ops in GLYPHS:
        out.append('static const GOp kGlyph%s[] = {' % name.capitalize())
        for op in ops:
            vals = list(op[1:]) + [0.0] * (6 - len(op[1:]))
            out.append("    { '%s', { %s } }," % (op[0], ', '.join('%.3ff' % v for v in vals)))
        out.append('};')
    out.append('static const GlyphDef kGlyphs[] = {')
    for name, ops in GLYPHS:
        out.append('    { kGlyph%s, %d },   // %s' % (name.capitalize(), len(ops), name))
    out.append('};')
    pts = ', '.join('{ %.2ff, %.2ff }' % p for p in BT_MARK)
    out.append('static const float kBtMark[6][2] = { %s };' % pts)
    return '\n'.join(out) + '\n'

def preview(path):
    from PIL import Image, ImageDraw
    S = 80; SS = 4
    W = (len(GLYPHS) + 1) * (S + 20) + 20
    img = Image.new('RGB', (W, S * 2 + 60), (40, 40, 40))
    d = ImageDraw.Draw(img)
    def draw(ops, ox, oy, size, color=(255, 255, 255)):
        sc = Image.new('RGBA', (size * SS, size * SS), (0, 0, 0, 0)); g = ImageDraw.Draw(sc)
        k = size * SS; w = max(2, int(round(0.14 * k)))
        for op in ops:
            t = op[0]; v = op[1:]
            if t == 'R': g.rounded_rectangle([v[0]*k, v[1]*k, (v[0]+v[2])*k, (v[1]+v[3])*k], radius=v[4]*k, fill=color)
            elif t == 'O': g.rounded_rectangle([v[0]*k, v[1]*k, (v[0]+v[2])*k, (v[1]+v[3])*k], radius=v[4]*k, outline=color, width=w)
            elif t == 'L': g.line([v[0]*k, v[1]*k, v[2]*k, v[3]*k], fill=color, width=w)
            elif t == 'A': g.arc([v[0]*k, v[1]*k, (v[0]+v[2])*k, (v[1]+v[3])*k], v[4], v[4]+v[5], fill=color, width=w)
            elif t == 'E': g.ellipse([v[0]*k, v[1]*k, (v[0]+v[2])*k, (v[1]+v[3])*k], fill=color)
            elif t == 'C': g.ellipse([v[0]*k, v[1]*k, (v[0]+v[2])*k, (v[1]+v[3])*k], outline=color, width=w)
            elif t == 'T': g.polygon([(v[0]*k, v[1]*k), (v[2]*k, v[3]*k), (v[4]*k, v[5]*k)], fill=color)
        sc = sc.resize((size, size), Image.BOX)
        img.paste(sc, (ox, oy), sc)
    for i, (name, ops) in enumerate(GLYPHS):
        draw(ops, 20 + i * (S + 20), 20, S)
        draw(ops, 20 + i * (S + 20), S + 40, 7 * 3 // 1 if False else 20)   # about the size on the screen x3
    img.save(path)
if __name__ == '__main__':
    if len(sys.argv) > 2 and sys.argv[1] == 'preview': preview(sys.argv[2])
    else: open(sys.argv[1], 'w', encoding='utf-8').write(cpp())
